import assert from 'node:assert/strict';
import { createPassportStore, PASSPORT_KEY } from './dist/passport.js';
const memory = new Map();
const storage = { getItem: key => memory.get(key), setItem: (key, value) => memory.set(key, value) };
memory.set(PASSPORT_KEY, '{broken');
const p = createPassportStore(storage, ['libai','sushi']);
assert.deepEqual(p.get().discovered, []);
assert.deepEqual(p.recordGame(['libai','libai','unknown']), ['libai']);
assert.deepEqual(p.recordGame(['libai','sushi']), ['sushi']);
assert.equal(p.get().games, 2);
p.favorite('libai'); p.favorite('libai'); p.favorite('unknown');
assert.deepEqual(p.get().favorites, []);
p.recordQuiz('sushi', { O: 150, C: -10, E: 55, A: 60, S: 70 });
assert.equal(p.get().results[0].scores.O, 100);
assert.equal(p.get().results[0].scores.C, 0);
p.recordQuiz('sushi', {}, false);
assert.equal(p.get().results.length, 1);
assert.deepEqual(createPassportStore(storage,['libai','sushi']).get().discovered,['libai','sushi']);
const blocked = createPassportStore({ getItem(){throw Error('blocked')}, setItem(){throw Error('quota')} },['libai']);
assert.deepEqual(blocked.recordGame(['libai']),['libai']);
assert.equal(blocked.get().persistent,false);
assert.deepEqual(p.clear().discovered, []);
console.log('Passport: corrupt saves, unknown IDs, deduplication, reload and blocked storage passed.');
